  function translateError(msg, lang) {
    if (!msg || lang === 'da') return msg;
    const idx = lang === 'en' ? 1 : 2;
    const tooLong = /^(.+) er for lang \(max (\d+) tegn\)\.$/.exec(msg);
    if (tooLong) {
      const name = (FIELD[tooLong[1]] || [tooLong[1], tooLong[1]])[idx - 1];
      return lang === 'en' ? `${name} is too long (max ${tooLong[2]} characters).` : `${name} ist zu lang (max. ${tooLong[2]} Zeichen).`;
    }
    for (const row of ERRORS) {
      if (typeof row[0] === 'string' ? row[0] === msg : row[0].test(msg)) {
        return typeof row[0] === 'string' ? row[idx] : msg.replace(row[0], row[idx]);
      }
    }
    return msg;
  }

